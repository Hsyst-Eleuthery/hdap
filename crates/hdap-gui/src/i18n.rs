impl Strings {
    pub fn for_lang(lang: Lang) -> &'static Strings {
        static PT: OnceLock<Strings> = OnceLock::new();
        static EN: OnceLock<Strings> = OnceLock::new();
        static ES: OnceLock<Strings> = OnceLock::new();
        static FR: OnceLock<Strings> = OnceLock::new();
        let slot = match lang {
            Lang::Pt => &PT,
            Lang::En => &EN,
            Lang::Es => &ES,
            Lang::Fr => &FR,
        };
        slot.get_or_init(|| match lang {
            Lang::Pt => pt(),
            Lang::En => en(),
            Lang::Es => es(),
            Lang::Fr => fr(),
        })
    }
}

